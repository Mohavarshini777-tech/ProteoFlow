// Helper to assemble preset
function createPreset(
  id: string,
  name: string,
  gene: string,
  organism: string,
  uniprotId: string,
  pdbId: string,
  seq: string,
  domains: DomainAnnotation[],
  activeSites: ActiveSiteResidue[],
  rawGoTerms: {
    molecularFunction: Array<{ id: string; name: string; evidence: string }>;
    biologicalProcess: Array<{ id: string; name: string; evidence: string }>;
    cellularComponent: Array<{ id: string; name: string; evidence: string }>;
  },
  interactions: {
    partners: any[];
    ligands: BoundLigand[];
    interfaceResidues: string[];
  },
  dnaInteractions: DnaInteraction[],
  literature: any[],
  pdbMetadata: any,
  dsspSecStruct: { helixPct: number; sheetPct: number; coilPct: number; source: string }
): ProteinData {
  const physico = calculatePhysicochemical(seq);
  const inSilicoSec = estimateSecondaryStructure(seq);

  // Parse GO terms with standardized evidence codes
  const goTerms = {
    molecularFunction: rawGoTerms.molecularFunction.map((t) => {
      const parsed = parseGoEvidence(t.evidence);
      return {
        id: t.id,
        name: t.name,
        category: 'molecular_function' as const,
        evidence: t.evidence,
        evidenceCode: parsed.code,
        evidenceCategory: parsed.category,
        evidenceExplanation: parsed.description,
        evidenceReliability: parsed.reliability,
        sourceDatabase: 'UniProtKB-GOA / Swiss-Prot Curated',
      };
    }),
    biologicalProcess: rawGoTerms.biologicalProcess.map((t) => {
      const parsed = parseGoEvidence(t.evidence);
      return {
        id: t.id,
        name: t.name,
        category: 'biological_process' as const,
        evidence: t.evidence,
        evidenceCode: parsed.code,
        evidenceCategory: parsed.category,
        evidenceExplanation: parsed.description,
        evidenceReliability: parsed.reliability,
        sourceDatabase: 'UniProtKB-GOA / Swiss-Prot Curated',
      };
    }),
    cellularComponent: rawGoTerms.cellularComponent.map((t) => {
      const parsed = parseGoEvidence(t.evidence);
      return {
        id: t.id,
        name: t.name,
        category: 'cellular_component' as const,
        evidence: t.evidence,
        evidenceCode: parsed.code,
        evidenceCategory: parsed.category,
        evidenceExplanation: parsed.description,
        evidenceReliability: parsed.reliability,
        sourceDatabase: 'UniProtKB-GOA / Swiss-Prot Curated',
      };
    }),
  };

  return {
    id,
    uniprotId,
    pdbId,
    name,
    gene,
    organism,
    sequence: seq,
    length: physico.length,
    molecularWeight: physico.molecularWeight,
    isoelectricPoint: physico.isoelectricPoint,
    netChargePh74: physico.netChargePh74,
    extinctionCoeff: physico.extinctionCoeff,
    hydrophobicRatio: physico.hydrophobicRatio,
    aminoAcidComposition: physico.composition,
    secondaryStructure: inSilicoSec, // In silico prediction
    dsspSecondaryStructure: dsspSecStruct, // Experimental structure measurement
    domains,
    activeSites,
    goTerms,
    interactions,
    dnaInteractions,
    literature,
    pdbMetadata: {
      ...pdbMetadata,
      structureType: 'experimental' as const,
      dsspSecondaryStructure: dsspSecStruct,
    },
    provenance: {
      sourceDatabase: 'UniProtKB/Swiss-Prot',
      isReviewed: true,
      retrievalDate: '2026-09-23T00:00:00Z',
      uniprotUrl: `https://www.uniprot.org/uniprotkb/${uniprotId}`,
      pdbUrl: `https://www.rcsb.org/structure/${pdbId}`,
      evidenceLevel: 'Experimental Structure & Curated Sequence',
      version: 'UniProtKB 2026_03 / PDB Archive',
    },
    variants: getCuratedVariantsForProtein(gene, uniprotId),
    hotspotSummary: calculateHotspotSummary(getCuratedVariantsForProtein(gene, uniprotId)),
  };
}

